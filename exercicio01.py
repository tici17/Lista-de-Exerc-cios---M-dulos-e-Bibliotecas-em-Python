# Exercício 1 — Conceito de Módulo
#
# Resposta:
# Um módulo em Python é um arquivo que contém códigos, como funções,
# variáveis e classes, que podem ser reutilizados em outros programas.
#
# Duas vantagens de dividir um programa em módulos são:
# 1. Facilitar a organização do código, deixando o programa mais fácil de entender.
# 2. Permitir o reaproveitamento de funções e códigos em diferentes programas.