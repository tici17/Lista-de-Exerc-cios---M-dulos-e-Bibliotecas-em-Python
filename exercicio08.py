# Exercício 8 — PyPI e pip
#
# a) O PyPI (Python Package Index) é um repositório onde são
# disponibilizados milhares de pacotes e bibliotecas para Python.
# Ele permite que os programadores encontrem e instalem ferramentas
# criadas por outras pessoas.
#
# b) O comando para instalar a biblioteca pandas é:
#
# pip install pandas
#
# c) O comando para desinstalar a biblioteca requests é:
#
# pip uninstall requests